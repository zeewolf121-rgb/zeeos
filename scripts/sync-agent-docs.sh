# Regenerates CLAUDE.md and AGENTS.md from docs/agent-context.md so both models
# share one source of truth. Use --check in CI to fail on drift.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$root/docs/agent-context.md"
codex_roles="$root/docs/agent-roles-codex.md"
header='<!-- GENERATED by scripts/sync-agent-docs.sh from docs/agent-context.md. Do not edit. -->'

render_claude() {
  printf '%s\n\n' "$header"
  cat "$src"
  printf '\n## Claude specifics\n\n'
  # shellcheck disable=SC2016  # backticks are literal Markdown
  printf 'Subagents live in `.claude/agents/`. Run them in parallel with one git worktree and branch each, at most 3 Claude agents at once (4 total with Codex), starts staggered 5 minutes apart (MISSION §11).\n'
}

render_agents() {
  printf '%s\n\n' "$header"
  cat "$src"
  printf '\n'
  cat "$codex_roles"
}

mode="${1:-write}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
render_claude >"$tmp/CLAUDE.md"
render_agents >"$tmp/AGENTS.md"

if [[ "$mode" == "--check" ]]; then
  status=0
  for f in CLAUDE.md AGENTS.md; do
    if ! diff -q "$tmp/$f" "$root/$f" >/dev/null 2>&1; then
      echo "::error file=$f::$f is out of date; run scripts/sync-agent-docs.sh"
      status=1
    fi
  done
  exit "$status"
fi

cp "$tmp/CLAUDE.md" "$tmp/AGENTS.md" "$root/"
echo "Updated CLAUDE.md and AGENTS.md"
